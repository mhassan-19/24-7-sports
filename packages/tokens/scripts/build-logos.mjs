// Generates src/logos.ts from the brand SVGs in assets/ so the mobile app (react-native-svg)
// can use the same logo markup as the website. Run after replacing a logo file:
//   node packages/tokens/scripts/build-logos.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'assets', f), 'utf8').trim();

const out = `// Generated by scripts/build-logos.mjs from assets/logo-*.svg. Do not edit by hand.
// Numerals use currentColor (Midnight on light, Bone on dark); the slash is Pulse Orange: the
// approved signature / signature-reversed versions.

export const logoPrimarySvg = ${JSON.stringify(read('logo-primary.svg'))};

export const logoMarkSvg = ${JSON.stringify(read('logo-mark.svg'))};

/** Width : height of both logo layouts. */
export const logoAspectRatio = 1177 / 980;
`;
writeFileSync(join(root, 'src', 'logos.ts'), out);
console.log('wrote src/logos.ts');
